"""Copy the shared markdown renderer (static/mdlite.js) into the self-contained widget.
The widget ships to other origins and cannot import it. Run after any change to mdlite.js;
tests/md_check.py fails if the two drift. Only the heading default differs (3, the widget's size)."""
from pathlib import Path
R = Path(__file__).resolve().parent.parent / "static"
m = (R / "mdlite.js").read_text()
body = m[m.index("var ESC0"):m.index("window.MuMd=")]
assert "o.h||4" in body
body = body.replace("o.h||4", "o.h||3")
# tests/md_check.py slices the widget from "function esc(" to "function mount(", so esc must come first.
first, rest = body.split("\n", 1)
assert first.startswith("var ESC0") and rest.startswith("function esc(")
esc_line, rest2 = rest.split("\n", 1)
body = esc_line + "\n" + first + "\n" + rest2
w = (R / "embed/widget.js").read_text()
B, E = "  /* BEGIN mdlite", "  /* END mdlite */\n\n"
if B in w:
    a, z = w.index(B), w.index(E) + len(E)
else:
    a, z = w.index("  function esc("), w.index("  function mount(")
new = w[:a] + "  /* BEGIN mdlite (generated by seed/sync_widget_md.py from static/mdlite.js: do not edit here) */\n" + body + E + w[z:]
(R / "embed/widget.js").write_text(new)
print("synced", len(body), "chars")
