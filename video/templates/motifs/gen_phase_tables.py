#!/usr/bin/env python3
"""Generate each motif README's phase table FROM its composition's own constants.

A README that DESCRIBES timings drifts the moment the composition is re-timed, and the
drift is silent and widens down the timeline. `boundary-and-the-index` reached a state
where every phase window in its README disagreed with its code - /modes was documented
at 25.89 and actually at 33.50, so a host seeking /modes off the README would have
rendered /notclaimed instead: the wrong content, silently, looking like a working render.

An assertion catches that after the fact. Generation makes it impossible, so the table
is written from the source of truth on every run.

The table lives between the markers below; everything outside them is hand-written and
is never touched.

    <!-- PHASES:BEGIN (generated by gen_phase_tables.py - do not hand-edit) -->
    ...
    <!-- PHASES:END -->

Run from the factory root:  .venv/bin/python videos/_motifs/gen_phase_tables.py
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
BEGIN = "<!-- PHASES:BEGIN (generated by gen_phase_tables.py - do not hand-edit) -->"
END = "<!-- PHASES:END -->"

PHASE_COMMENT = re.compile(r"//\s+/(\w+)\s+([\d.]+)\s*-\s*([\d.]+)\s*(.*)")
DURATION = re.compile(r'data-duration="([\d.]+)"')
CONST = re.compile(r"const\s+(AT_[A-Z0-9_]+)\s*=\s*([\d.]+);\s*(?://\s*(.*))?")


def table_for(comp: Path):
    text = comp.read_text()
    phases = [(m.group(1), float(m.group(2)), float(m.group(3)), m.group(4).strip())
              for m in PHASE_COMMENT.finditer(text)]
    if not phases:
        return None
    dur = DURATION.findall(text)
    total = float(dur[0]) if dur else None
    consts = [(m.group(1), float(m.group(2)), (m.group(3) or "").strip())
              for m in CONST.finditer(text)]

    lines = [BEGIN, "",
             "| Phase | Window | Notes |", "|---|---|---|"]
    for name, a, b, note in phases:
        lines.append(f"| `/{name}` | {a:.2f}-{b:.2f} | {note} |")
    if total is not None:
        lines.append("")
        lines.append(f"Internal timeline **{total}s**. The last phase may end before the "
                     f"declared duration; a host plays the window it needs.")
    if consts:
        lines.append("")
        lines.append("Event constants, read from the composition:")
        lines.append("")
        for k, v, c in consts:
            lines.append(f"- `{k}` {v}{('  -  ' + c) if c else ''}")
    lines += ["",
              "*Generated from the composition's own phase comments and `AT_` constants. "
              "A README that describes timings drifts on the next re-time; this one "
              "cannot.*", "", END]
    return "\n".join(lines)


def main():
    comps = sorted(ROOT.glob("*/composition.html"))
    if not comps:
        sys.exit("no compositions found - zero of zero is not a pass")
    wrote = skipped = 0
    for comp in comps:
        rd = comp.parent / "README.md"
        tbl = table_for(comp)
        if tbl is None:
            print(f"  {comp.parent.name}: no phase comments, nothing to generate")
            skipped += 1
            continue
        if not rd.exists():
            print(f"  {comp.parent.name}: no README")
            skipped += 1
            continue
        txt = rd.read_text()
        if BEGIN in txt and END in txt:
            new = txt[:txt.index(BEGIN)] + tbl + txt[txt.index(END) + len(END):]
        else:
            new = txt.rstrip() + "\n\n## Phases\n\n" + tbl + "\n"
        if new != txt:
            rd.write_text(new)
            print(f"  {comp.parent.name}: phase table generated "
                  f"({tbl.count(chr(10) + '| `/')} phases)")
            wrote += 1
        else:
            print(f"  {comp.parent.name}: already current")
    print(f"\n{wrote} README(s) written, {skipped} skipped")
    if wrote == 0 and skipped == len(comps):
        sys.exit("nothing generated at all - the phase-comment pattern may have changed")


if __name__ == "__main__":
    main()
